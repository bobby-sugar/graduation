function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function buildWorldviewDescription(world) {
  const related = (world.relatedOcs && world.relatedOcs.length ? world.relatedOcs.join("、") : "（可在工作站为 OC 绑定所属世界观）");
  const prose = [
    world.intro,
    "",
    "【设定信息】",
    `一句话设定：${world.summaryHint}`,
    `类型：${world.type}`,
    `时代/背景：${world.era}`,
    `地域/舞台：${world.regions}`,
    `阵营/势力：${world.factions}`,
    `核心冲突：${world.coreConflict}`,
    `核心主题：${world.keyTheme}`,
    "世界规则：",
    ...world.rules.map((rule, index) => `${index + 1}. ${rule}`),
    `关联作品/系列：${world.series}`,
    `关联 OC：${related}`,
    "",
    "【时间线】",
    ...world.timeline,
    "",
    "【区域图层】",
    ...world.locations,
    "",
    "【叙事入口】",
    ...world.storyHooks.map((hook) => `· ${hook}`),
  ].join("\n");

  const payload = {
    v: 1,
    kind: "worldview",
    worldview: {
      summaryHint: world.summaryHint,
      chips: world.chips,
      relatedCharacters: world.relatedOcs || [],
    },
  };

  return `${prose}\n\n${CARD_JSON_MARKER}\n${JSON.stringify(payload)}`;
}

async function purgePreviousBatch() {
  const prev = await prisma.artwork.findMany({
    where: { tags: { contains: SEED_TAG } },
    select: { id: true },
  });
  const ids = prev.map((r) => r.id);
  if (ids.length === 0) return;

  const comments = await prisma.comment.findMany({
    where: { artworkId: { in: ids } },
    select: { id: true },
  });
  const commentIds = comments.map((c) => c.id);
  if (commentIds.length) {
    await prisma.commentLike.deleteMany({ where: { commentId: { in: commentIds } } });
  }

  let guard = 0;
  while ((await prisma.comment.count({ where: { artworkId: { in: ids } } })) > 0 && guard < 80) {
    guard += 1;
    await prisma.comment.deleteMany({
      where: { artworkId: { in: ids }, replies: { none: {} } },
    });
  }

  await prisma.artworkLike.deleteMany({ where: { artworkId: { in: ids } } });
  await prisma.favorite.deleteMany({ where: { artworkId: { in: ids } } });
  await prisma.view.deleteMany({ where: { artworkId: { in: ids } } });
  await prisma.notification.deleteMany({ where: { artworkId: { in: ids } } });
  await prisma.artwork.deleteMany({ where: { id: { in: ids } } });
}

async function main() {
  const sourceDir =
    process.env.OC_WORLVIEW_SOURCE_DIR || process.env.OC_GALLERY_SOURCE_DIR || DEFAULT_SOURCE_DIR;
  if (!fs.existsSync(sourceDir)) {
    throw new Error(`源目录不存在: ${sourceDir}\n请设置 OC_WORLVIEW_SOURCE_DIR 或 OC_GALLERY_SOURCE_DIR。`);
  }

  const users = await prisma.user.findMany({
    orderBy: { id: "asc" },
    select: { id: true, username: true },
  });
  if (users.length < 1) {
    throw new Error("数据库中至少需要 1 个用户。请先运行 prisma seed 创建账号。");
  }

  if (!fs.existsSync(UPLOAD_DIR)) {
    fs.mkdirSync(UPLOAD_DIR, { recursive: true });
  }

  await purgePreviousBatch();

  const baseTs = Date.now();
  let created = 0;

  for (let i = 0; i < WORLDS.length; i += 1) {
    const world = WORLDS[i];
    const src = path.join(sourceDir, world.file);
    if (!fs.existsSync(src)) {
      throw new Error(`缺少源文件: ${src}\n请确认 PNG 已保存在 Cursor 项目 assets 目录。`);
    }

    const destName = `wv-seed-${baseTs}-${String(i + 1).padStart(2, "0")}.png`;
    const destAbs = path.join(UPLOAD_DIR, destName);
    fs.copyFileSync(src, destAbs);

    const author = users[i % users.length];
    const tagsWithMarker = `${world.tags},${SEED_TAG}`;
    const imageUrl = `/uploads/${destName}`;

    await prisma.artwork.create({
      data: {
        title: world.title,
        description: buildWorldviewDescription(world),
        imageUrl,
        category: "worldview",
        ocPrivacy: "public",
        authorId: author.id,
        tags: tagsWithMarker,
        likes: world.likes ?? 0,
        views: world.views ?? 0,
      },
    });

    created += 1;
  }

  // eslint-disable-next-line no-console
  console.log(
    JSON.stringify(
      {
        ok: true,
        created,
        sourceDir,
        users: users.length,
        message: `已写入 ${created} 条公开世界观（标记 ${SEED_TAG}），图片已复制到 uploads/wv-seed-*`,
      },
      null,
      2,
    ),
  );
}

main()
  .catch((e) => {
    // eslint-disable-next-line no-console
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
